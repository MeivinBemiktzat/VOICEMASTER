/**
 * כל ההנחיות (prompts) ל-Gemini במקום אחד.
 * הנוסח זהה לאתר המקורי, פרט לתסריט הפודקאסט שהורחב לשני דוברים בשמות מוגדרים.
 */
import { toneChoices } from "./catalogs";

export const prompts = {
  magicWrite: (topic: string) =>
    `כתוב טקסט קצר ומקצועי לקריינות בעברית בנושא הבא: "${topic}". השתמש בעברית בלבד. אל תכתוב כותרות, רשימות, כוכביות, סולמיות, סימוני Markdown, מספרי סעיפים, קוד או תגיות. החזר רק את הטקסט הנקי.`,

  smartEdit: (instruction: string, text: string) =>
    `${instruction} על הטקסט הבא: "${text}". החזר בעברית בלבד טקסט נקי, בלי כותרות, רשימות, כוכביות, סולמיות, סימוני Markdown, מספרים, קוד או תגיות.`,

  translate: (text: string) =>
    `שכתב את הטקסט הבא לעברית טבעית וברורה שמתאימה לקריינות: "${text}". החזר רק טקסט בעברית ללא כותרות, רשימות, כוכביות, סולמיות, Markdown, קוד או תגיות.`,

  summarize: (text: string) =>
    `סכם בעברית את הטקסט הבא לשלושה משפטים קצרים וברורים לקריינות: "${text}". אל תשתמש ברשימות, כוכביות, סולמיות, Markdown, קוד או תגיות.`,

  analyzeTone: (text: string) =>
    `נתח את הטקסט הבא ובחר סגנון הקראה אחד בלבד מהרשימה: ${toneChoices}. החזר רק את מילת הסגנון באנגלית ללא הסבר. הטקסט: "${text}"`,

  vocalize: (text: string) =>
    `הוסף ניקוד דקדוקי מלא ומדויק לטקסט הבא בעברית: "${text}". החזר רק את הטקסט המנוקד, בלי כותרות, רשימות, כוכביות, סולמיות או הסברים.`,

  podcastScript: (topic: string, nameA: string, nameB: string, length: string) =>
    `כתוב בעברית בלבד דו-שיח ${length} וטבעי לפודקאסט בין שני דוברים בנושא "${topic}". שמות הדוברים הם ${nameA} ו${nameB}. כל שורה חייבת להתחיל בשם הדובר, נקודתיים ואז הטקסט, למשל "${nameA}: שלום וברוכים הבאים". הדוברים מתחלפים בכל שורה. אל תשתמש בכותרות, רשימות, כוכביות, סולמיות, Markdown, קוד או תגיות. החזר רק את הדו-שיח הנקי.`,

  narration: (styleInstruction: string, text: string) =>
    `בצע קריינות בעברית. סגנון ההקראה: ${styleInstruction}. הקרא בדיוק את הטקסט הבא ללא הוספת מילים: ${text}`,

  podcastNarration: (styleInstruction: string, text: string) =>
    `הקרא את השיחה הבאה בעברית כפודקאסט. סגנון ההקראה: ${styleInstruction}. הקרא בדיוק את הטקסט ללא הוספת מילים:\n${text}`,
};
